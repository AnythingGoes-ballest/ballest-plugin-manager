"""Embeds the host's own UI pictures (src/host/pictures/*.png: slot silhouettes, the globe, the glow, ...) into
src/host/pictures.inc, so they ship inside version.dll; ux::Picture writes each to the host's cache folder the first time
it is used and loads it from there.

    python tools/gen_ui_pictures.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src', 'host', 'pictures')
OUT = os.path.join(HERE, '..', 'src', 'host', 'pictures.inc')

lines = ['// Generated by tools/gen_ui_pictures.py from src/host/pictures/*.png. Do not edit: run the script again.']
names = sorted(f for f in os.listdir(SRC) if f.endswith('.png'))
for n in names:
    data = open(os.path.join(SRC, n), 'rb').read()
    var = 'k_' + n[:-4].replace('-', '_')
    body = ','.join(str(b) for b in data)
    lines.append('const unsigned char %s[] = {%s};' % (var, body))
lines.append('const Embedded kPictures[] = {')
for n in names:
    var = 'k_' + n[:-4].replace('-', '_')
    lines.append('    {"%s", %s, sizeof %s},' % (n, var, var))
lines.append('};')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(OUT), len(names), 'pictures')
